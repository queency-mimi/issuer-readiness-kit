// Normative shapes: SPEC.md section 5. JSON Schema: schemas/action-request.schema.json.
import type { Hex32 } from "../hash.ts";
import type { ControlKind, IsoTime, PrincipalId, StellarAddress } from "../policy/types.ts";

export type RequestState =
  | "proposed"
  | "approved"
  | "signed"
  | "submitted"
  | "rejected"
  | "expired"
  | "cancelled";

export const TERMINAL_STATES: readonly RequestState[] = ["submitted", "rejected", "expired", "cancelled"];

/** Typed, stable JSON form of a Soroban ScVal (SPEC section 5.2). */
export type ScValJson =
  | { type: "bool"; value: boolean }
  | { type: "void" }
  | { type: "u32" | "i32"; value: number }
  | { type: "u64" | "i64" | "u128" | "i128" | "u256" | "i256"; value: string }
  | { type: "symbol" | "string"; value: string }
  | { type: "bytes"; value: string }
  | { type: "address"; value: StellarAddress }
  | { type: "vec"; value: ScValJson[] }
  | { type: "map"; value: { key: ScValJson; value: ScValJson }[] };

export interface Intent {
  networkPassphrase: string;
  /** Transaction source account (pays the fee, sequence number). */
  source: StellarAddress;
  contract: string;
  function: string;
  args: ScValJson[];
  /** SHA-256 (tagged) of the canonical authorised-invocation tree(s), see SPEC section 7.2. */
  invocationTreeDigest: Hex32;
}

export interface ClearSigningSummary {
  /** One line a human checker reads. Generated by the kit, never supplied by the maker. */
  headline: string;
  /** Ordered key/value facts, e.g. ["token", "C..."], ["amount", "1250.0000000 USDC"]. */
  facts: [string, string][];
  /** Nodes of the authorised tree rendered as indented lines. */
  tree: string[];
  warnings: string[];
}

export interface ActionRequest {
  version: 1;
  /** Equals requestHash (content-addressed). */
  id: Hex32;
  policyHash: Hex32;
  maker: PrincipalId;
  createdAt: IsoTime;
  expiresAt: IsoTime;
  kind: "invoke" | "control";
  controlKind?: ControlKind;
  intent: Intent;
  summary: ClearSigningSummary;
  /** Base64 XDR of the unsigned TransactionEnvelope as simulated at proposal time. */
  unsignedTxXdr: string;
  /** Free-text business reason. Stored hashed in the audit log (SPEC section 8.4). */
  reasonHash?: Hex32;
  /** Client-chosen nonce so two identical proposals have different ids. 16-64 chars [A-Za-z0-9_-]. */
  nonce: string;
}

export type Attestation =
  | { scheme: "stellar-sep53"; address: StellarAddress; signatureBase64: string }
  | { scheme: "host-asserted"; assertedBy: string };

/** The exact object that an approver signs (canonicalised, then tagged-hashed). SPEC section 5.4. */
export interface ApprovalStatement {
  v: 1;
  kind: "mkr-approval";
  requestId: Hex32;
  policyHash: Hex32;
  intentDigest: Hex32;
  decision: "approve" | "reject";
  approver: PrincipalId;
  at: IsoTime;
  nonce: string;
}

export interface Approval {
  statement: ApprovalStatement;
  attestation: Attestation;
}

export type RequestEvent =
  | { type: "proposed"; at: IsoTime; request: ActionRequest }
  | { type: "approval_recorded"; at: IsoTime; approval: Approval }
  | { type: "signature_collected"; at: IsoTime; slotId: string; signerId: string; shareIndex?: number }
  | { type: "signing_completed"; at: IsoTime; signedTxXdrHash: Hex32 }
  | { type: "submitted"; at: IsoTime; txHash: Hex32; signedTxXdrHash?: Hex32 }
  | { type: "cancelled"; at: IsoTime; by: PrincipalId }
  | { type: "expired"; at: IsoTime };

export interface RequestRecord {
  request: ActionRequest;
  state: RequestState;
  approvals: Approval[];
  /** Set when the approval threshold was met; signing is allowed from this time + cooldown. */
  thresholdMetAt?: IsoTime;
  signingEligibleAt?: IsoTime;
  collectedSlotIds: string[];
  signedTxXdrHash?: Hex32;
  txHash?: Hex32;
  /** Number of events applied; equals the audit sequence of the last event for this request. */
  version: number;
}
