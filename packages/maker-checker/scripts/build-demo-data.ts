// `pnpm demo:data`: builds web/src/data/demo.json from committed fixtures only (no network, no clock), so the
// console builds offline and every figure it shows traces to a file with provenance.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { verifyEntries } from "../src/audit/log.ts";
import type { AuditEntry } from "../src/audit/types.ts";
import { sha256Hex } from "../src/hash.ts";
import { policyHash } from "../src/policy/hash.ts";
import { parsePolicyDoc } from "../src/policy/parse.ts";

const root = new URL("..", import.meta.url).pathname;
const read = (p: string) => readFileSync(root + p, "utf8");

const run = JSON.parse(read("../../fixtures/maker-checker/testnet/e2e-run.json"));
const provenance = JSON.parse(read("../../fixtures/maker-checker/testnet/e2e-run.provenance.json"));
const audit = read("../../fixtures/maker-checker/testnet/e2e-audit.jsonl").trim().split("\n").map((l) => JSON.parse(l) as AuditEntry);
const rep = verifyEntries(audit);
if (!rep.ok) throw new Error("recorded audit log does not verify; refusing to build demo data");

const exampleText = read("../../fixtures/maker-checker/policies/example-treasury.policy.json");
const ex = parsePolicyDoc(exampleText);
if (!("doc" in ex)) throw new Error("example policy invalid");
const expect = JSON.parse(read("../../fixtures/maker-checker/policies/invalid/EXPECT.json")).expect as Record<string, string>;
const invalid = Object.entries(expect).map(([file, code]) => ({ file, code, text: read("../../fixtures/maker-checker/policies/invalid/" + file) }));
const wasm = readFileSync(root + "../../fixtures/maker-checker/wasm/rwa-demo.wasm");

const testFiles = readdirSync(root + "test").filter((f) => f.endsWith(".test.ts"));

const out = {
  note: "Generated by scripts/build-demo-data.ts from committed fixtures. Do not edit by hand.",
  recorded: {
    run,
    provenance,
    audit,
    verifiedAtBuild: rep,
  },
  example: { file: "fixtures/maker-checker/policies/example-treasury.policy.json", text: exampleText, policyHash: policyHash(ex.doc) },
  invalid,
  wasm: { file: "fixtures/maker-checker/wasm/rwa-demo.wasm", bytes: wasm.length, sha256: sha256Hex(wasm), matchesRun: sha256Hex(wasm) === run.world.deploy.wasmSha256 },
  sources: {
    testFiles: testFiles.length,
    fixtures: ["fixtures/maker-checker/testnet/e2e-run.json", "fixtures/maker-checker/testnet/e2e-audit.jsonl", "fixtures/maker-checker/testnet/e2e-run.provenance.json", "fixtures/maker-checker/policies/", "fixtures/maker-checker/wasm/rwa-demo.wasm"].map((f) => ({ file: f, bytes: statSync(root + "../../" + f).isDirectory() ? undefined : statSync(root + "../../" + f).size })),
  },
};
writeFileSync(root + "web/src/data/demo.json", JSON.stringify(out, null, 1) + "\n");
process.stdout.write(`demo.json: ${run.steps.length} steps, ${audit.length} audit entries (verified), ${invalid.length} invalid fixtures\n`);
